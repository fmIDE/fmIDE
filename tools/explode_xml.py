#!/usr/bin/env python3
"""Rebuild src/exploded from the current SaXML using Malte Bastian's exploder."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET

repo = Path(__file__).resolve().parents[1]
source = repo / 'src/xml'
target = repo / 'src/exploded'
marker = '.fmide-generated'
binary = os.environ.get('FM_XML_EXPLODER_BIN') or str(repo / '.tools/fm-xml-export-exploder')
if not Path(binary).is_file():
    binary = shutil.which('fm-xml-export-exploder') or binary
if not Path(binary).is_file():
    raise SystemExit('Exploder missing. See src/README.md or set FM_XML_EXPLODER_BIN.')
xmls = sorted(source.glob('*.xml'))
if not xmls:
    raise SystemExit('No XML exports found in src/xml.')
for path in xmls:
    ET.parse(path)
if target.exists() and not (target / marker).is_file():
    raise SystemExit('Refusing to replace an unmarked src/exploded directory.')
version = subprocess.check_output([binary, '--version'], text=True).strip()
with tempfile.TemporaryDirectory(prefix='.explode-', dir=repo / 'src') as scratch:
    staging = Path(scratch) / 'generated'
    subprocess.run([binary, '--lossless', '--output_tree', 'db', str(source), str(staging)], check=True)
    files = [p for p in staging.rglob('*') if p.is_file()]
    if not files:
        raise SystemExit('Exploder produced no files; previous output preserved.')
    for path in staging.rglob('*.xml'):
        ET.parse(path)
    (staging / marker).write_text('Generated by tools/explode_xml.py. Regenerate; do not edit.\n')
    manifest = {
        'tool': version,
        'options': ['--lossless', '--output_tree', 'db'],
        'inputs': {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in xmls},
        'generatedFiles': len(files),
    }
    (staging / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    backup = Path(scratch) / 'previous'
    if target.exists():
        target.rename(backup)
    try:
        staging.rename(target)
    except BaseException:
        if backup.exists():
            backup.rename(target)
        raise
print(f'Generated {len(files)} files in {target} using {version}.')
